// 关卡敌方阵容的统一读法。Phase 2 会把 enemy 扩展成带身份的对象（{id, name}），
// 这里先收敛成一个入口，免得 battle.js 和 campaign-check.mjs 各写一份解析。
export function enemyIds(stage){
  return stage.enemy.map(e => typeof e === 'string' ? e : e.id);
}
