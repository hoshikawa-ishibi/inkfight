// 关卡敌方阵容的统一读法：条目可以是纯 id 字符串，也可以是带身份的 {id, name}。
// 收敛成一个入口，免得 battle.js 和 campaign-check.mjs 各写一份解析。
export function enemyIds(stage){
  return stage.enemy.map(e => typeof e === 'string' ? e : e.id);
}

// ── 战役主角与队友解锁 ─────────────────────────────────────
//
